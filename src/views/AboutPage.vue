<script>

import HeaderSection from "../components/HeaderSection.vue";
import StatisticsSection from "../components/StatisticsSection.vue";
import VisionMission from "../components/VisionMission.vue";
import CTASection from "../components/CTASection.vue";
import FooterSection from "../components/FooterSection.vue";


export default {

    name: "AboutPage",

    components: {
        HeaderSection,
        StatisticsSection,
        VisionMission,
        CTASection,
        FooterSection
    },


    data() {

        return {

            /* =================================================
               TEAM DATA
            ================================================== */

            teamMembers: [

                {
                    name: "Smita",
                    role: "Technology & Business",
                    image: "/images/about/smita.png",
                    number: "01"
                },

                {
                    name: "Shrikant",
                    role: "Technology & Solutions",
                    image: "/images/about/shrikant.png",
                    number: "02"
                },

                {
                    name: "Pooja",
                    role: "Technology & Operations",
                    image: "/images/about/pooja.jpg",
                    number: "03"
                },

                {
                    name: "Mamata",
                    role: "Business & Technology",
                    image: "/images/about/mamata.jpg",
                    number: "04"
                },

                {
                    name: "Girish",
                    role: "Technology & Solutions",
                    image: "/images/about/girish.jpg",
                    number: "05"
                },

                {
                    name: "Dinesh",
                    role: "Technology & Operations",
                    image: "/images/about/dinesh.jpg",
                    number: "06"
                }

            ],


            teamIndex: 0,

            teamInterval: null,

            teamTouchStartX: 0,

            teamTouchEndX: 0,

            teamWindowWidth:
                typeof window !== "undefined"
                    ? window.innerWidth
                    : 1200

        };

    },


    computed: {

        /* =====================================================
           NUMBER OF VISIBLE CARDS
        ====================================================== */

        teamVisibleCount() {

            if (this.teamWindowWidth <= 700) {
                return 1;
            }

            if (this.teamWindowWidth <= 1050) {
                return 2;
            }

            return 4;

        },


        /* =====================================================
           MAXIMUM SLIDER INDEX
        ====================================================== */

        teamMaxIndex() {

            return Math.max(
                0,
                this.teamMembers.length -
                this.teamVisibleCount
            );

        },


        /* =====================================================
           NUMBER OF DOTS
        ====================================================== */

        teamPageCount() {

            return this.teamMaxIndex + 1;

        },


        /* =====================================================
           SLIDER TRACK STYLE

           IMPORTANT:
           We calculate percentage based on visible cards.
           This avoids the old translateX calculation issue.
        ====================================================== */

        teamTrackStyle() {

            const visible = this.teamVisibleCount;

            const gap =
                visible === 1
                    ? 0
                    : 18;

            const cardWidth =
                `calc((100% - ${(visible - 1) * gap}px) / ${visible})`;

            const move =
                `calc(${this.teamIndex} * (${cardWidth} + ${gap}px) * -1)`;

            return {

                "--team-visible": visible,

                "--team-gap":
                    `${gap}px`,

                "--team-card-width":
                    cardWidth,

                transform:
                    `translate3d(${move}, 0, 0)`

            };

        }

    },


    mounted() {

        window.addEventListener(
            "resize",
            this.handleResize
        );

        this.startTeamSlider();

    },


    beforeUnmount() {

        window.removeEventListener(
            "resize",
            this.handleResize
        );

        this.stopTeamSlider();

    },


    methods: {

        /* =====================================================
           RESIZE
        ====================================================== */

        handleResize() {

            this.teamWindowWidth =
                window.innerWidth;

            if (
                this.teamIndex >
                this.teamMaxIndex
            ) {

                this.teamIndex =
                    this.teamMaxIndex;

            }

        },


        /* =====================================================
           NEXT
        ====================================================== */

        nextTeam() {

            if (this.teamIndex < this.teamMaxIndex) {
                this.teamIndex++;
            } else {
                this.teamIndex = 0;
            }

        },


        /* =====================================================
           PREVIOUS
        ====================================================== */

        previousTeam() {

            if (this.teamIndex > 0) {

                this.teamIndex--;

            } else {

                this.teamIndex =
                    this.teamMaxIndex;

            }

        },


        /* =====================================================
           GO TO SPECIFIC SLIDE
        ====================================================== */

        goToTeam(index) {

            this.teamIndex = Math.min(
                Math.max(index, 0),
                this.teamMaxIndex
            );

            this.restartTeamSlider();

        },


        /* =====================================================
           START AUTOPLAY
        ====================================================== */

        startTeamSlider() {

            this.stopTeamSlider();

            this.teamInterval =
                setInterval(() => {

                    this.nextTeam();

                }, 3000);

        },


        /* =====================================================
           STOP AUTOPLAY
        ====================================================== */

        stopTeamSlider() {

            if (this.teamInterval) {

                clearInterval(
                    this.teamInterval
                );

                this.teamInterval = null;

            }

        },


        /* =====================================================
           RESTART AUTOPLAY
        ====================================================== */

        restartTeamSlider() {

            this.stopTeamSlider();

            this.startTeamSlider();

        },


        /* =====================================================
           PAUSE ON HOVER
        ====================================================== */

        pauseTeamSlider() {

            this.stopTeamSlider();

        },


        /* =====================================================
           RESUME AFTER HOVER
        ====================================================== */

        resumeTeamSlider() {

            this.startTeamSlider();

        },


        /* =====================================================
           TOUCH START
        ====================================================== */

        handleTouchStart(event) {

            if (
                !event.changedTouches ||
                !event.changedTouches.length
            ) {
                return;
            }

            this.teamTouchStartX =
                event.changedTouches[0].clientX;

        },


        /* =====================================================
           TOUCH END
        ====================================================== */

        handleTouchEnd(event) {

            if (
                !event.changedTouches ||
                !event.changedTouches.length
            ) {
                return;
            }

            this.teamTouchEndX =
                event.changedTouches[0].clientX;

            const distance =
                this.teamTouchStartX -
                this.teamTouchEndX;

            const minimumSwipe =
                50;

            if (
                Math.abs(distance) <
                minimumSwipe
            ) {
                return;
            }

            if (distance > 0) {

                this.nextTeam();

            } else {

                this.previousTeam();

            }

            this.restartTeamSlider();

        },


        /* =====================================================
           IMAGE ERROR FALLBACK
        ====================================================== */

        handleImageError(event) {

            event.target.style.display =
                "none";

            const parent =
                event.target.parentElement;

            if (parent) {

                parent.classList.add(
                    "image-missing"
                );

            }

        }

    }

};

</script>


